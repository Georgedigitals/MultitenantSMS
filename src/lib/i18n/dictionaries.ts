export type SupportedLanguage = 'en' | 'fr' | 'es' | 'pt' | 'ar';

export interface LanguageMeta {
  code: SupportedLanguage;
  label: string;
  nativeLabel: string;
  dir: 'ltr' | 'rtl';
}

export const SUPPORTED_LANGUAGES: LanguageMeta[] = [
  { code: 'en', label: 'English', nativeLabel: 'English', dir: 'ltr' },
  { code: 'fr', label: 'French', nativeLabel: 'Français', dir: 'ltr' },
  { code: 'es', label: 'Spanish', nativeLabel: 'Español', dir: 'ltr' },
  { code: 'pt', label: 'Portuguese', nativeLabel: 'Português', dir: 'ltr' },
  { code: 'ar', label: 'Arabic (RTL)', nativeLabel: 'العربية', dir: 'rtl' },
];

export function isSupportedLanguage(code: string): code is SupportedLanguage {
  return code === 'en' || code === 'fr' || code === 'es' || code === 'pt' || code === 'ar';
}

export function getLanguageDir(code: string): 'ltr' | 'rtl' {
  return code === 'ar' ? 'rtl' : 'ltr';
}

