export function translate(lang: SupportedLanguage, key: string, fallback?: string): string {
  return DICTIONARIES[lang]?.[key] || DICTIONARIES.en[key] || fallback || key;
}

export function translatePhrase(lang: SupportedLanguage, text: string): string {
  if (!text || lang === 'en') return text;
  const trimmed = text.trim();
  const exact = PHRASE_MAP[lang]?.[trimmed];
  if (exact) return exact;

  // Handle dynamic platform-name phrases like "Explore School Platform" or "What School Platform does"
  if (trimmed.startsWith('Explore ')) {
    const rest = trimmed.slice('Explore '.length);
    const prefixes: Record<Exclude<SupportedLanguage, 'en'>, string> = {
      fr: 'Découvrir ',
      es: 'Explorar ',
      pt: 'Explorar ',
      ar: 'استكشف ',
    };
    return `${prefixes[lang]}${rest}`;
  }
  if (trimmed.startsWith('What ') && trimmed.endsWith(' does')) {
    const middle = trimmed.slice('What '.length, -' does'.length);
    const templates: Record<Exclude<SupportedLanguage, 'en'>, string> = {
      fr: `Ce que fait ${middle}`,
      es: `Qué hace ${middle}`,
      pt: `O que ${middle} faz`,
      ar: `ماذا تقدم ${middle}`,
    };
    return templates[lang];
  }
  return text;
}
